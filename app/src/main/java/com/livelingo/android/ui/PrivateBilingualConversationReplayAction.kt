package com.livelingo.android.ui

import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.Row
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import com.livelingo.android.BilingualReplayCaption
import com.livelingo.android.BilingualReplayPair
import com.livelingo.android.LocalSpeechPace
import com.livelingo.android.PrivateBilingualConversationReplay

/**
 * Isolated Compose sub-screen: avoid adding more generated bytecode to the
 * already large live transcript composable. Only finished RAM captions are
 * eligible; selecting this action never sends or stores content.
 */
@Composable
internal fun PrivateBilingualConversationReplayAction(
    captions: List<BilingualReplayCaption>,
    sourceCode: String,
    targetCode: String,
    enabled: Boolean,
    notice: String,
    onPlay: (List<BilingualReplayPair>, LocalSpeechPace) -> Unit,
    onStop: () -> Unit
) {
    val eligible = PrivateBilingualConversationReplay.available(
        captions, sourceCode, targetCode
    )
    Column(
        modifier = Modifier.fillMaxWidth(),
        verticalArrangement = Arrangement.spacedBy(4.dp)
    ) {
        Text(
            "Tweetalig terugluisteren · ${sourceCode.uppercase()} → " +
                "${targetCode.uppercase()} · ${eligible.size} afgeronde zinnen (maximaal 8)",
            style = MaterialTheme.typography.bodySmall
        )
        Text(
            "Alleen bestaande lokale vertalingen, op verzoek. " +
                "Eerst het origineel, dan de vertaling. " +
                "Vereist twee geïnstalleerde offline Android-stemmen.",
            style = MaterialTheme.typography.bodySmall
        )
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            TextButton(
                enabled = enabled && eligible.isNotEmpty(),
                onClick = { onPlay(eligible, LocalSpeechPace.NORMAL) }
            ) { Text("▶ Tweetalig") }
            TextButton(
                enabled = enabled && eligible.isNotEmpty(),
                onClick = { onPlay(eligible, LocalSpeechPace.SLOW) }
            ) { Text("▶ Rustig") }
        }
        TextButton(onClick = onStop) { Text("■ Stop tweetalig voorlezen") }
        if (notice.isNotBlank()) {
            Text(notice, style = MaterialTheme.typography.bodySmall)
        }
    }
}
